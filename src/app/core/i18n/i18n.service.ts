@Injectable({
  providedIn: 'root'
})
export class I18nService {
  private currentLang = new BehaviorSubject<'ar' | 'en'>('ar');
  public currentLang$ = this.currentLang.asObservable();

  private translations: Record<string, Translations> = { ar, en };

  get lang(): 'ar' | 'en' {
    return this.currentLang.value;
  }

  setLang(lang: 'ar' | 'en') {
    this.currentLang.next(lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem('lang', lang);
  }

  init() {
    const saved = localStorage.getItem('lang') as 'ar' | 'en' | null;
    if (saved) {
      this.setLang(saved);
    }
  }

  t(key: string): string {
    const keys = key.split('.');
    let value: any = this.translations[this.lang];
    for (const k of keys) {
      if (value && typeof value === 'object' && k in value) {
        value = value[k];
      } else {
        return key;
      }
    }
    return typeof value === 'string' ? value : key;
  }
}
